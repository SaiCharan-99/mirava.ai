"""`make types`: pydantic schemas → web/src/types/generated.ts."""

from __future__ import annotations

import sys
from pathlib import Path

from pydantic import BaseModel

from shared.schemas import ALL_MODELS

OUT = Path("web/src/types/generated.ts")


def ts_type(node: dict) -> str:
    """TypeScript type for one JSON-schema node."""
    if "$ref" in node:
        return node["$ref"].split("/")[-1]
    if "enum" in node:
        return " | ".join(f'"{v}"' if isinstance(v, str) else str(v) for v in node["enum"])
    if "const" in node:
        return f'"{node["const"]}"'
    if "anyOf" in node:
        return " | ".join(ts_type(x) for x in node["anyOf"])
    t = node.get("type")
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        if "prefixItems" in node:
            return "[" + ", ".join(ts_type(x) for x in node["prefixItems"]) + "]"
        return f"{ts_type(node.get('items', {}))}[]"
    if t == "object":
        if "properties" in node:
            return "{ " + "; ".join(f"{k}: {ts_type(v)}" for k, v in node["properties"].items()) + " }"
        extra = node.get("additionalProperties")
        if isinstance(extra, dict):
            names = node.get("propertyNames", {})
            key = ts_type(names) if names else "string"
            return f"Partial<Record<{key}, {ts_type(extra)}>>" if names else f"Record<string, {ts_type(extra)}>"
        return "Record<string, unknown>"
    return "unknown"


def interface(model: type[BaseModel]) -> str:
    """One `export interface` block."""
    sch = model.model_json_schema(ref_template="#/$defs/{model}")
    req = set(sch.get("required", []))
    lines = [f"export interface {model.__name__} {{"]
    for name, prop in sch.get("properties", {}).items():
        opt = "" if name in req else "?"
        lines.append(f"  {name}{opt}: {ts_type(prop)};")
    lines.append("}")
    return "\n".join(lines)


def render() -> str:
    """Full generated.ts contents."""
    head = "// GENERATED by `make types` from shared/schemas — do not edit.\n/* eslint-disable */\n"
    return head + "\n\n".join(interface(m) for m in ALL_MODELS) + "\n"


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(ALL_MODELS)} interfaces)")
    sys.exit(0)
